use crate::taxonomy::Subsystem;
use dacc_core::{nonempty_str, taxon};
use dacc_knowledge::{Breaking, DocStatus};

dacc_knowledge::adr!(
    title: "The pilot's promises are held where the registry can show it",
    status: DocStatus::Active,
    channel: crate::taxonomy::channel::Public,
    subsystems: &[taxon!(Subsystem, Pilot), taxon!(Subsystem, Docs)],
    context: r"
        rfc-2026-001 states six promises as its invariants: a reference to a
        record that no longer exists does not compile; a work item cannot be
        landed without a gate proof recorded on the same tree; every commit
        after the switch carries a basis naming a work item in the commit's own
        tree; a superseded decision names its successor, and that successor
        exists; no work item lands with a radius above its slice's ceiling; and
        converting a Markdown record to the registry and back loses nothing.

        The promises are dacc's, enforced by the toolchain this tree runs — the
        scan, the journal fold, the gate. The contract check that closes a
        slice (W-030) wants their executors in the registry: an invariant
        record per promise, with live anchors on the code that holds it and on
        a test that demonstrates it. The anchor scan read only crates/, and the
        build and the xtask gate — where these promises are actually held —
        were outside it. Without the records the contract has no executor and
        every slice against rfc-2026-001 stays open.
    ",
    decision: r"
        The six promises become invariant records i0067 to i0072, each naming
        rfc-2026-001 as the specification whose contract it holds.

        The anchor scan is extended over doc/ and xtask/: the build script and
        the gate are where this tree can show the promises hold, so that is
        where their anchors live. Each promise names both an executor and a
        test that demonstrates it:

        - the reference constants are generated by the scan in build.rs, and a
          test walks the records' references against the registries;
        - the journal fold in build.rs refuses a landing without its gate, and
          a test walks the journal proving every landed work carries one on the
          same tree;
        - the commit gate in xtask gains the basis rule — a subject without a
          Dacc-Work trailer naming a work item of the tree is refused — and
          every rule of that gate is shown a fixture that breaks it;
        - the superseded variant carries its successor as a reference that
          compiles, and a test walks the decisions proving each successor
          exists;
        - the radius ceiling is asserted in build.rs over every work item, and
          a test runs the same predicate;
        - the converted records keep their sections in the context field, and
          a test guards that residue beside v0001's byte-for-byte measurement.

        The invariant registry moves onto dacc_knowledge's Invariant and
        Review, which retires the local types of adr-2026-057 as it promised.
        The INV- key moves into the statement, so code and prose go on naming
        the same guarantee.

        Every invariant names the specification whose contract it holds, by
        one rule, applied in order: the statement listed in a specification's
        invariants names that specification; otherwise the subject decides —
        the engine's convergence is the baseline (rfc-2026-002), what the
        engine and an executor say to each other is the wire (rfc-2026-003),
        evaluation and the values it decides from are the configuration
        (rfc-2026-004), and the verbs and the typed plan are the command line
        (rfc-2026-005). Where a statement is listed twice, the subject's home
        wins.
    ",
    trade_offs: &[
        "The contract check passes for every specification, and the slices close on evidence in this tree rather than on an argument about where the enforcement lives.",
        "The cost is two more files carrying anchors — build.rs and xtask couple themselves to the registry; the alternative was executors named in prose, which is what the check exists to refuse.",
        "The basis rule is enforced twice — by dacc's msg-check and by the xtask gate, and the cost of the duplication is a second fixture suite; accepted where the gate is the project's own.",
        "The conversion promise keeps a measured past and a guarded residue: the byte-for-byte proof is v0001's, and the cost of guarding the residue is one test that looks at what remains readable.",
    ],
    constraints: &[
        "The anchor scan covers crates/, doc/ and xtask/; an anchor outside them does not compile.",
        "Every invariant names its specification, by the stated rule.",
        "The INV- key stays in the record — in the statement — so prose and SECURITY.md keep naming the same guarantee.",
        "A promise's record names an executor anchor and a test anchor, both live.",
    ],
    authors: nonempty_str!["Anishchuk Sergei"],
    decided_at: dacc_core::date!(2026, 10, 3),
    breaking: Breaking::No,
    code_refs: &[],
    related_rfcs: &[crate::rfc::rfc_2026_001],
    introduces_norm: false,
);
